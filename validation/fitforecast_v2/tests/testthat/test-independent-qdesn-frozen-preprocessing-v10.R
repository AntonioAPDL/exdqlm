iqfp_load <- function() {
  source(file.path(harness_root,"R/independent_qdesn_frozen_preprocessing_v10.R"),local=FALSE)
  iqfp_v10_source(repo_root)
}

test_that("saved MCMC replay preserves joint parameter rows and rejects corruption", {
  iqfp_load()
  f <- tempfile(fileext=".csv")
  p <- data.frame(draw=1:4,sigma=1:4,gamma=c(-.1,.1,.2,.3),beta_1=5:8,beta_2=9:12)
  write.csv(p,f,row.names=FALSE)
  x <- iqfp_v10_parameters(f)
  expect_s3_class(x,"exal_mcmc")
  expect_equal(unname(x$summary$beta_mean),c(6.5,10.5))
  a <- exal_posterior_draws(x,3,seed=71)
  b <- exal_posterior_draws(x,3,seed=71)
  expect_equal(a,b)
  expect_equal(a$sigma,p$sigma[a$source_draw_index])
  expect_equal(a$gamma,p$gamma[a$source_draw_index])
  p$sigma[1] <- 0;write.csv(p,f,row.names=FALSE)
  expect_error(iqfp_v10_parameters(f))
  p$sigma[1] <- 1;p$draw[1] <- 2;write.csv(p,f,row.names=FALSE)
  expect_error(iqfp_v10_parameters(f))
})

test_that("effective preprocessing and feature-prefix checks do not trust flags", {
  iqfp_load()
  a <- list(X=matrix(1:6,3,2),states=list(H_all=list(matrix(1:8,4,2))),
    meta=list(lag_center=c(3,3),lag_scale=c(2,2),preprocessing_frozen_from_override=TRUE))
  b <- a
  expect_true(all(iqfp_v10_assert_prefix(a,b,list(center=3,scale=2))$pass))
  b$meta$lag_center[1] <- 4
  expect_error(iqfp_v10_assert_prefix(a,b,list(center=3,scale=2)),"prefix differs")
  b <- a;b$X[1,1] <- b$X[1,1]+.1
  expect_error(iqfp_v10_assert_prefix(a,b,list(center=3,scale=2)))
  b <- a;b$states$H_all[[1]][1,1] <- 9
  expect_error(iqfp_v10_assert_prefix(a,b,list(center=3,scale=2)))
})

test_that("repair configs explicitly separate saved basis from new scientific fits", {
  iqfp_load()
  f <- tempfile(fileext=".json")
  r <- list(job_id="source",case_id="case",pair_role="control",stage="pilot",config_path=f)
  iqfr_v2_write_json(r,f)
  cfg <- iqfp_v10_config(r,"mcmc",repo_root,tempdir())
  expect_identical(cfg$preprocessing_policy,"saved_training_basis_including_observed_warmup")
  expect_identical(cfg$scientific_role,"compatibility_repair_not_article_replacement")
  expect_identical(cfg$reference_config_sha256,iqfr_v2_sha256(f))
  body <- paste(deparse(iqfp_v10_prepare),collapse="\n")
  expect_false(grepl("iqmb_v9_fit_mcmc|exal_mcmc_fit\\(",body))
  expect_match(body,"saved_training_draws",fixed=TRUE)
  expect_match(body,"iqps_v8_fit_check",fixed=TRUE)
})

