source('validation/autodesn/load_checkout.R')
Rcpp::sourceCpp('src/autodesn_rhs.cpp',cacheDir='validation/autodesn/remediation/artifacts/cpp',showOutput=FALSE)
set.seed(12);y<-sin((1:90)/3)+rnorm(90,sd=.2)
spec<-list(list(D=1,n=4,n_tilde=integer(0),m=2,alpha=.4,rho=.5,seed=311,washout=5,pi_in=1,pi_w=1))
b<-autodesn_build_bank(y,spec,conditioning=5,washout=10,standardize_features=TRUE,normalize_features=FALSE)
e<-autodesn_extend_bank(b,list(lags=1:3,prior='grouped'),list(periods=c(12,18),harmonics=3))
f<-autodesn_fit_bank(e,n_burn=10,n_mcmc=20,beta_prior='rhs',rhs_control=list(tau0=.001,slab_scale=1),backend='cpp',seed=29)
print(f$draws[1:3,]);fc<-forecast_paths(f,4,nd=3,inner_paths=2,seed=44);print(fc$yrep)
g<-autodesn_fit_bank(e,n_burn=10,n_mcmc=20,beta_prior='rhs',rhs_control=list(tau0=.001,slab_scale=1),variance_control=list(type='sv'),backend='cpp',seed=29)
fil<-autodesn_filter(g,1:3,particles=32,seed=19)
print(forecast_paths(g,4,draw_index=1:3,inner_paths=2,state_filter=fil,seed=44)$yrep)
g2<-autodesn_update_history(g,c(.1,.4));fil2<-autodesn_filter(g2,1:3,particles=32,previous=fil,seed=20)
print(forecast_paths(g2,4,draw_index=1:3,inner_paths=2,state_filter=fil2,seed=44)$yrep)
