root<-normalizePath('validation/autodesn/remediation')
library(exdqlm,lib.loc=file.path(root,'artifacts/s3_library'))
signature_check<-tools::checkS3methods('exdqlm',lib.loc=file.path(root,'artifacts/s3_library'))
stopifnot(length(signature_check)==0L)
files<-c('test-autodesn-extended.R','test-autodesn-statistics-cache.R','test-autodesn-checkpoint.R')
paths<-normalizePath(file.path('tests/testthat',files));fixtures<-normalizePath('tests/testthat/fixtures')
directory<-tempfile('s3-installed-',tmpdir='/tmp');dir.create(directory)
stopifnot(all(file.copy(paths,directory)),file.copy(fixtures,directory,recursive=TRUE))
if(nzchar(Sys.which('git'))){
 g<-suppressWarnings(system2('git',c('-C',shQuote(directory),'rev-parse','--show-toplevel'),stdout=TRUE,stderr=FALSE))
 stopifnot(!is.null(attr(g,'status')),attr(g,'status')!=0L)
}
old<-getwd();setwd(directory)
results<-lapply(files,function(n)testthat::test_file(n,reporter='summary',stop_on_failure=FALSE))
setwd(old);saveRDS(results,file.path(root,'artifacts/s3_api_installed_test_results.rds'))
s<-do.call(rbind,lapply(results,as.data.frame))
record<-list(complete=TRUE,S3_signature_inconsistencies=length(signature_check),tests=nrow(s),assertions=sum(s$nb),passed=sum(s$passed),failures=sum(s$failed),errors=sum(s$error),warnings=sum(s$warning),outside_git=TRUE,installed_database_sha256=digest::digest(file=system.file('R/exdqlm.rdb',package='exdqlm'),algo='sha256'),scope='Fresh installed extension tests outside Git and complete S3 signature check; not a complete package check')
jsonlite::write_json(record,file.path(root,'evidence/s3_api_installed_tests.json'),pretty=TRUE,auto_unbox=TRUE)
unlink(directory,recursive=TRUE)
stopifnot(record$failures==0L,record$errors==0L,record$warnings==0L)
cat('INSTALLED_S3_AND_EXTENSION_TESTS_COMPLETE\n')
